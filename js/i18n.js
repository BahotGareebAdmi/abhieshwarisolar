(function () {
  function getLang() {
    return localStorage.getItem('as-lang') || 'en';
  }

  function t(key) {
    const lang = getLang();
    return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  }
  window.t = t;
  window.getLang = getLang;

  function applyLanguage(lang) {
    document.documentElement.setAttribute('lang', lang === 'hi' ? 'hi' : 'en');

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', t(key));
    });

    const toggle = document.getElementById('langToggle');
    if (toggle) {
      toggle.textContent = lang === 'hi' ? 'EN' : 'हिं';
      toggle.setAttribute('aria-label', lang === 'hi' ? 'Switch to English' : 'हिंदी में बदलें');
    }
  }
  window.applyLanguage = applyLanguage;

  function setLanguage(lang) {
    localStorage.setItem('as-lang', lang);
    applyLanguage(lang);
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
  }
  window.setLanguage = setLanguage;

  document.addEventListener('DOMContentLoaded', () => {
    applyLanguage(getLang());
    const toggle = document.getElementById('langToggle');
    if (toggle) {
      toggle.addEventListener('click', () => {
        setLanguage(getLang() === 'hi' ? 'en' : 'hi');
      });
    }
  });
})();
